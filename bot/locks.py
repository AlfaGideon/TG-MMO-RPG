"""Поюзерные замки для операций с деньгами/предметами.

aiogram обрабатывает апдейты параллельно, а Telegram охотно досылает
колбэк повторно (двойной тап, ретрай после таймаута клиента). В итоге
два одинаковых «Купить»/«Скрафтить» успевали прочитать одинаковое
состояние и списать/начислить дважды. Замок на пользователя убирает
весь класс таких гонок разом.
"""
import asyncio

_locks: dict[int, asyncio.Lock] = {}


def for_user(user_id: int) -> asyncio.Lock:
    """Замок конкретного пользователя (создаётся лениво)."""
    lock = _locks.get(user_id)
    if lock is None:
        lock = asyncio.Lock()
        _locks[user_id] = lock
    return lock
